"""Pure in-memory outbox, worker and emergency-stop contracts."""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Protocol, TypeAlias, runtime_checkable


@dataclass(frozen=True, slots=True)
class WorkScopeId:
    """A locally registered scope that may own outbox work."""

    value: str

    def __post_init__(self) -> None:
        if not isinstance(self.value, str) or not self.value.strip():
            raise ValueError("work scope identifier must be a non-blank string")


@dataclass(frozen=True, slots=True)
class WorkIdempotencyKey:
    """A unique local key that permits only one job over the outbox lifetime."""

    value: str

    def __post_init__(self) -> None:
        if not isinstance(self.value, str) or not self.value.strip():
            raise ValueError("idempotency key must be a non-blank string")


@dataclass(frozen=True, slots=True)
class OutboxJobId:
    """A deterministic identifier generated by the in-memory outbox."""

    value: str

    def __post_init__(self) -> None:
        if not isinstance(self.value, str) or not self.value.strip():
            raise ValueError("outbox job identifier must be a non-blank string")


@dataclass(frozen=True, slots=True)
class WorkerId:
    """An explicitly named local worker identity."""

    value: str

    def __post_init__(self) -> None:
        if not isinstance(self.value, str) or not self.value.strip():
            raise ValueError("worker identifier must be a non-blank string")


@dataclass(frozen=True, slots=True)
class JobDescription:
    """A non-secret, local description of the work to be processed."""

    value: str

    def __post_init__(self) -> None:
        if not isinstance(self.value, str) or not self.value.strip():
            raise ValueError("job description must be a non-blank string")


@dataclass(frozen=True, slots=True)
class JobVersion:
    """An expected-state token that prevents stale transitions."""

    value: int

    def __post_init__(self) -> None:
        if not isinstance(self.value, int) or isinstance(self.value, bool):
            raise TypeError("job version must be an integer")
        if self.value < 0:
            raise ValueError("job version must not be negative")

    def next(self) -> JobVersion:
        """Create the next immutable state version."""
        return JobVersion(value=self.value + 1)


@dataclass(frozen=True, slots=True)
class AuditSequence:
    """One-based sequence number of a local audit record."""

    value: int

    def __post_init__(self) -> None:
        if not isinstance(self.value, int) or isinstance(self.value, bool):
            raise TypeError("audit sequence must be an integer")
        if self.value < 1:
            raise ValueError("audit sequence must be positive")


class JobStatus(str, Enum):
    """The complete set of local outbox job states."""

    PENDING = "pending"
    CLAIMED = "claimed"
    COMPLETED = "completed"
    FAILED = "failed"
    BLOCKED = "blocked"


class EmergencyStopState(str, Enum):
    """Whether new or outstanding work must be stopped locally."""

    ACTIVE = "active"
    STOPPED = "stopped"


class AuditKind(str, Enum):
    """Auditable transitions created only by local state changes."""

    ENQUEUED = "enqueued"
    CLAIMED = "claimed"
    COMPLETED = "completed"
    SENDER_FAILED = "sender_failed"
    BLOCKED_BY_EMERGENCY_STOP = "blocked_by_emergency_stop"


class OutboxRejectionReason(str, Enum):
    """Finite reasons for fail-closed outbox operations."""

    UNKNOWN_SCOPE = "unknown_scope"
    DUPLICATE_IDEMPOTENCY_KEY = "duplicate_idempotency_key"
    EMERGENCY_STOP_ACTIVE = "emergency_stop_active"
    JOB_NOT_FOUND = "job_not_found"
    JOB_NOT_PENDING = "job_not_pending"
    JOB_NOT_CLAIMED = "job_not_claimed"
    STALE_EXPECTED_VERSION = "stale_expected_version"
    WORKER_MISMATCH = "worker_mismatch"


@dataclass(frozen=True, slots=True)
class OutboxJob:
    """A single local job represented without payloads or provider details."""

    job_id: OutboxJobId
    scope: WorkScopeId
    idempotency_key: WorkIdempotencyKey
    description: JobDescription
    status: JobStatus
    version: JobVersion
    claimed_by: WorkerId | None

    def __post_init__(self) -> None:
        if not isinstance(self.job_id, OutboxJobId):
            raise TypeError("job_id must be an OutboxJobId")
        if not isinstance(self.scope, WorkScopeId):
            raise TypeError("scope must be a WorkScopeId")
        if not isinstance(self.idempotency_key, WorkIdempotencyKey):
            raise TypeError("idempotency_key must be a WorkIdempotencyKey")
        if not isinstance(self.description, JobDescription):
            raise TypeError("description must be a JobDescription")
        if not isinstance(self.status, JobStatus):
            raise TypeError("status must be a JobStatus")
        if not isinstance(self.version, JobVersion):
            raise TypeError("version must be a JobVersion")
        if self.claimed_by is not None and not isinstance(self.claimed_by, WorkerId):
            raise TypeError("claimed_by must be a WorkerId or None")
        if self.status is JobStatus.CLAIMED and self.claimed_by is None:
            raise ValueError("claimed jobs must identify their worker")
        if self.status is not JobStatus.CLAIMED and self.claimed_by is not None:
            raise ValueError("only claimed jobs may identify a worker")

    def claimed(self, worker_id: WorkerId) -> OutboxJob:
        """Return the next state after one worker has claimed a pending job."""
        if self.status is not JobStatus.PENDING:
            raise ValueError("only pending jobs may be claimed")
        return OutboxJob(
            job_id=self.job_id,
            scope=self.scope,
            idempotency_key=self.idempotency_key,
            description=self.description,
            status=JobStatus.CLAIMED,
            version=self.version.next(),
            claimed_by=worker_id,
        )

    def completed(self) -> OutboxJob:
        """Return the next state after successful local fake delivery."""
        return self._finalized(status=JobStatus.COMPLETED)

    def failed(self) -> OutboxJob:
        """Return the next state after a local fake sender failure."""
        return self._finalized(status=JobStatus.FAILED)

    def blocked(self) -> OutboxJob:
        """Return the next state after emergency stop blocks outstanding work."""
        if self.status not in (JobStatus.PENDING, JobStatus.CLAIMED):
            raise ValueError("only outstanding jobs may be blocked")
        return OutboxJob(
            job_id=self.job_id,
            scope=self.scope,
            idempotency_key=self.idempotency_key,
            description=self.description,
            status=JobStatus.BLOCKED,
            version=self.version.next(),
            claimed_by=None,
        )

    def _finalized(self, status: JobStatus) -> OutboxJob:
        if self.status is not JobStatus.CLAIMED:
            raise ValueError("only claimed jobs may be finalized")
        return OutboxJob(
            job_id=self.job_id,
            scope=self.scope,
            idempotency_key=self.idempotency_key,
            description=self.description,
            status=status,
            version=self.version.next(),
            claimed_by=None,
        )


@dataclass(frozen=True, slots=True)
class AuditEntry:
    """One in-memory audit record with no timestamps, payloads or secrets."""

    sequence: AuditSequence
    job_id: OutboxJobId
    kind: AuditKind
    worker_id: WorkerId | None

    def __post_init__(self) -> None:
        if not isinstance(self.sequence, AuditSequence):
            raise TypeError("sequence must be an AuditSequence")
        if not isinstance(self.job_id, OutboxJobId):
            raise TypeError("job_id must be an OutboxJobId")
        if not isinstance(self.kind, AuditKind):
            raise TypeError("kind must be an AuditKind")
        if self.worker_id is not None and not isinstance(self.worker_id, WorkerId):
            raise TypeError("worker_id must be a WorkerId or None")


@dataclass(frozen=True, slots=True)
class SenderSuccess:
    """A fake sender completed a local delivery attempt."""


@dataclass(frozen=True, slots=True)
class SenderFailure:
    """A fake sender failed locally without revealing any provider response."""


SenderResult: TypeAlias = SenderSuccess | SenderFailure


@runtime_checkable
class OutboxSender(Protocol):
    """A provider-free boundary for a local delivery attempt."""

    def deliver(self, job: OutboxJob) -> SenderResult:
        """Attempt delivery using only the strongly typed local job."""


class FakeSenderScenario(str, Enum):
    """Deterministic fake outcomes available to tests and local consumers."""

    SUCCESS = "success"
    FAILURE = "failure"


@dataclass(slots=True)
class FakeOutboxSender:
    """A fake-only sender that records attempts but never contacts a service."""

    scenario: FakeSenderScenario
    delivery_attempt_count: int = 0

    def __post_init__(self) -> None:
        if not isinstance(self.scenario, FakeSenderScenario):
            raise TypeError("scenario must be a FakeSenderScenario")
        if not isinstance(self.delivery_attempt_count, int) or isinstance(
            self.delivery_attempt_count, bool
        ):
            raise TypeError("delivery_attempt_count must be an integer")
        if self.delivery_attempt_count < 0:
            raise ValueError("delivery_attempt_count must not be negative")

    def deliver(self, job: OutboxJob) -> SenderResult:
        """Record a local fake attempt and return its configured typed outcome."""
        if not isinstance(job, OutboxJob):
            raise TypeError("job must be an OutboxJob")
        self.delivery_attempt_count += 1
        if self.scenario is FakeSenderScenario.SUCCESS:
            return SenderSuccess()
        return SenderFailure()


@dataclass(frozen=True, slots=True)
class EnqueueAccepted:
    """A newly enqueued job and its next immutable core snapshot."""

    core: InMemoryReliabilityCore
    job: OutboxJob


@dataclass(frozen=True, slots=True)
class EnqueueRejected:
    """A rejected enqueue operation that leaves the core snapshot unchanged."""

    core: InMemoryReliabilityCore
    reason: OutboxRejectionReason


EnqueueResult: TypeAlias = EnqueueAccepted | EnqueueRejected


@dataclass(frozen=True, slots=True)
class ClaimAccepted:
    """One worker owns a claimed job in the next core snapshot."""

    core: InMemoryReliabilityCore
    job: OutboxJob


@dataclass(frozen=True, slots=True)
class ClaimRejected:
    """A rejected claim that leaves the core snapshot unchanged."""

    core: InMemoryReliabilityCore
    reason: OutboxRejectionReason


ClaimResult: TypeAlias = ClaimAccepted | ClaimRejected


@dataclass(frozen=True, slots=True)
class ProcessCompleted:
    """A claimed job completed through a fake sender."""

    core: InMemoryReliabilityCore
    job: OutboxJob


@dataclass(frozen=True, slots=True)
class ProcessSenderFailed:
    """A fake sender failure was recorded and made terminal locally."""

    core: InMemoryReliabilityCore
    job: OutboxJob


@dataclass(frozen=True, slots=True)
class ProcessRejected:
    """A stale, unsafe or invalid processing request was not attempted."""

    core: InMemoryReliabilityCore
    reason: OutboxRejectionReason


ProcessResult: TypeAlias = ProcessCompleted | ProcessSenderFailed | ProcessRejected


@dataclass(frozen=True, slots=True)
class InMemoryReliabilityCore:
    """Immutable local snapshots for outbox, worker claim and stop semantics."""

    scopes: tuple[WorkScopeId, ...]
    jobs: tuple[OutboxJob, ...]
    audit_entries: tuple[AuditEntry, ...]
    emergency_stop: EmergencyStopState

    def __post_init__(self) -> None:
        if not isinstance(self.scopes, tuple):
            raise TypeError("scopes must be a tuple")
        if not isinstance(self.jobs, tuple):
            raise TypeError("jobs must be a tuple")
        if not isinstance(self.audit_entries, tuple):
            raise TypeError("audit_entries must be a tuple")
        if not isinstance(self.emergency_stop, EmergencyStopState):
            raise TypeError("emergency_stop must be an EmergencyStopState")
        _require_unique_scopes(self.scopes)
        _require_unique_jobs(self.jobs)
        _require_valid_audit_sequence(self.audit_entries)

    @classmethod
    def with_scopes(
        cls, scopes: tuple[WorkScopeId, ...]
    ) -> InMemoryReliabilityCore:
        """Create a local core whose usable work scopes are explicitly registered."""
        no_jobs: tuple[OutboxJob, ...] = ()
        no_audit_entries: tuple[AuditEntry, ...] = ()
        return cls(
            scopes=scopes,
            jobs=no_jobs,
            audit_entries=no_audit_entries,
            emergency_stop=EmergencyStopState.ACTIVE,
        )

    def enqueue(
        self,
        scope: WorkScopeId,
        idempotency_key: WorkIdempotencyKey,
        description: JobDescription,
    ) -> EnqueueResult:
        """Add one scoped job only when the local safety guards allow it."""
        if not isinstance(scope, WorkScopeId):
            raise TypeError("scope must be a WorkScopeId")
        if not isinstance(idempotency_key, WorkIdempotencyKey):
            raise TypeError("idempotency_key must be a WorkIdempotencyKey")
        if not isinstance(description, JobDescription):
            raise TypeError("description must be a JobDescription")
        if self.emergency_stop is EmergencyStopState.STOPPED:
            return EnqueueRejected(
                core=self, reason=OutboxRejectionReason.EMERGENCY_STOP_ACTIVE
            )
        if scope not in self.scopes:
            return EnqueueRejected(core=self, reason=OutboxRejectionReason.UNKNOWN_SCOPE)
        if self._has_idempotency_key(idempotency_key):
            return EnqueueRejected(
                core=self, reason=OutboxRejectionReason.DUPLICATE_IDEMPOTENCY_KEY
            )
        job = OutboxJob(
            job_id=OutboxJobId(value=f"outbox-{len(self.jobs) + 1:04d}"),
            scope=scope,
            idempotency_key=idempotency_key,
            description=description,
            status=JobStatus.PENDING,
            version=JobVersion(value=0),
            claimed_by=None,
        )
        next_core = self._with_audit(
            jobs=self.jobs + (job,),
            job=job,
            kind=AuditKind.ENQUEUED,
            worker_id=None,
        )
        return EnqueueAccepted(core=next_core, job=job)

    def claim(self, job_id: OutboxJobId, worker_id: WorkerId) -> ClaimResult:
        """Let exactly one named worker claim a currently pending job."""
        if not isinstance(job_id, OutboxJobId):
            raise TypeError("job_id must be an OutboxJobId")
        if not isinstance(worker_id, WorkerId):
            raise TypeError("worker_id must be a WorkerId")
        job = self._find_job(job_id)
        if job is None:
            return ClaimRejected(core=self, reason=OutboxRejectionReason.JOB_NOT_FOUND)
        if self.emergency_stop is EmergencyStopState.STOPPED:
            return ClaimRejected(
                core=self, reason=OutboxRejectionReason.EMERGENCY_STOP_ACTIVE
            )
        if job.status is not JobStatus.PENDING:
            return ClaimRejected(core=self, reason=OutboxRejectionReason.JOB_NOT_PENDING)
        claimed_job = job.claimed(worker_id)
        next_core = self._with_audit(
            jobs=self._replace_job(claimed_job),
            job=claimed_job,
            kind=AuditKind.CLAIMED,
            worker_id=worker_id,
        )
        return ClaimAccepted(core=next_core, job=claimed_job)

    def process_claimed(
        self,
        job_id: OutboxJobId,
        worker_id: WorkerId,
        expected_version: JobVersion,
        sender: OutboxSender,
    ) -> ProcessResult:
        """Run one fake delivery only after ownership and version checks pass."""
        if not isinstance(job_id, OutboxJobId):
            raise TypeError("job_id must be an OutboxJobId")
        if not isinstance(worker_id, WorkerId):
            raise TypeError("worker_id must be a WorkerId")
        if not isinstance(expected_version, JobVersion):
            raise TypeError("expected_version must be a JobVersion")
        if not isinstance(sender, OutboxSender):
            raise TypeError("sender must implement the OutboxSender contract")
        job = self._find_job(job_id)
        if job is None:
            return ProcessRejected(core=self, reason=OutboxRejectionReason.JOB_NOT_FOUND)
        if job.status is not JobStatus.CLAIMED:
            return ProcessRejected(core=self, reason=OutboxRejectionReason.JOB_NOT_CLAIMED)
        if job.version != expected_version:
            return ProcessRejected(
                core=self, reason=OutboxRejectionReason.STALE_EXPECTED_VERSION
            )
        if job.claimed_by != worker_id:
            return ProcessRejected(core=self, reason=OutboxRejectionReason.WORKER_MISMATCH)
        if self.emergency_stop is EmergencyStopState.STOPPED:
            return ProcessRejected(
                core=self, reason=OutboxRejectionReason.EMERGENCY_STOP_ACTIVE
            )
        sender_result = sender.deliver(job)
        if isinstance(sender_result, SenderSuccess):
            completed_job = job.completed()
            next_core = self._with_audit(
                jobs=self._replace_job(completed_job),
                job=completed_job,
                kind=AuditKind.COMPLETED,
                worker_id=worker_id,
            )
            return ProcessCompleted(core=next_core, job=completed_job)
        if isinstance(sender_result, SenderFailure):
            failed_job = job.failed()
            next_core = self._with_audit(
                jobs=self._replace_job(failed_job),
                job=failed_job,
                kind=AuditKind.SENDER_FAILED,
                worker_id=worker_id,
            )
            return ProcessSenderFailed(core=next_core, job=failed_job)
        raise TypeError("sender must return a SenderSuccess or SenderFailure")

    def activate_emergency_stop(self) -> InMemoryReliabilityCore:
        """Block every outstanding job and retain a local audit record for each."""
        if self.emergency_stop is EmergencyStopState.STOPPED:
            return self
        stopped_core = InMemoryReliabilityCore(
            scopes=self.scopes,
            jobs=self.jobs,
            audit_entries=self.audit_entries,
            emergency_stop=EmergencyStopState.STOPPED,
        )
        job: OutboxJob
        for job in self.jobs:
            if job.status in (JobStatus.PENDING, JobStatus.CLAIMED):
                blocked_job = job.blocked()
                stopped_core = stopped_core._with_audit(
                    jobs=stopped_core._replace_job(blocked_job),
                    job=blocked_job,
                    kind=AuditKind.BLOCKED_BY_EMERGENCY_STOP,
                    worker_id=job.claimed_by,
                )
        return stopped_core

    def job(self, job_id: OutboxJobId) -> OutboxJob:
        """Read one known job from this immutable local snapshot."""
        if not isinstance(job_id, OutboxJobId):
            raise TypeError("job_id must be an OutboxJobId")
        job = self._find_job(job_id)
        if job is None:
            raise LookupError("outbox job does not exist")
        return job

    def _find_job(self, job_id: OutboxJobId) -> OutboxJob | None:
        job: OutboxJob
        for job in self.jobs:
            if job.job_id == job_id:
                return job
        return None

    def _has_idempotency_key(self, idempotency_key: WorkIdempotencyKey) -> bool:
        job: OutboxJob
        for job in self.jobs:
            if job.idempotency_key == idempotency_key:
                return True
        return False

    def _replace_job(self, replacement: OutboxJob) -> tuple[OutboxJob, ...]:
        return tuple(
            replacement if job.job_id == replacement.job_id else job
            for job in self.jobs
        )

    def _with_audit(
        self,
        jobs: tuple[OutboxJob, ...],
        job: OutboxJob,
        kind: AuditKind,
        worker_id: WorkerId | None,
    ) -> InMemoryReliabilityCore:
        entry = AuditEntry(
            sequence=AuditSequence(value=len(self.audit_entries) + 1),
            job_id=job.job_id,
            kind=kind,
            worker_id=worker_id,
        )
        return InMemoryReliabilityCore(
            scopes=self.scopes,
            jobs=jobs,
            audit_entries=self.audit_entries + (entry,),
            emergency_stop=self.emergency_stop,
        )


@dataclass(frozen=True, slots=True)
class OutboxWorker:
    """A named worker façade over the pure in-memory core transition guard."""

    worker_id: WorkerId

    def __post_init__(self) -> None:
        if not isinstance(self.worker_id, WorkerId):
            raise TypeError("worker_id must be a WorkerId")

    def process(
        self,
        core: InMemoryReliabilityCore,
        job_id: OutboxJobId,
        expected_version: JobVersion,
        sender: OutboxSender,
    ) -> ProcessResult:
        """Process a job under this worker identity and the core's state guard."""
        if not isinstance(core, InMemoryReliabilityCore):
            raise TypeError("core must be an InMemoryReliabilityCore")
        return core.process_claimed(
            job_id=job_id,
            worker_id=self.worker_id,
            expected_version=expected_version,
            sender=sender,
        )


def _require_unique_scopes(scopes: tuple[WorkScopeId, ...]) -> None:
    seen_scopes: tuple[WorkScopeId, ...] = ()
    scope: WorkScopeId
    for scope in scopes:
        if not isinstance(scope, WorkScopeId):
            raise TypeError("scopes must contain WorkScopeId values")
        if scope in seen_scopes:
            raise ValueError("scopes must be unique")
        seen_scopes += (scope,)


def _require_unique_jobs(jobs: tuple[OutboxJob, ...]) -> None:
    seen_job_ids: tuple[OutboxJobId, ...] = ()
    seen_keys: tuple[WorkIdempotencyKey, ...] = ()
    job: OutboxJob
    for job in jobs:
        if not isinstance(job, OutboxJob):
            raise TypeError("jobs must contain OutboxJob values")
        if job.job_id in seen_job_ids:
            raise ValueError("outbox job identifiers must be unique")
        if job.idempotency_key in seen_keys:
            raise ValueError("outbox idempotency keys must be unique")
        seen_job_ids += (job.job_id,)
        seen_keys += (job.idempotency_key,)


def _require_valid_audit_sequence(audit_entries: tuple[AuditEntry, ...]) -> None:
    expected_sequence = 1
    entry: AuditEntry
    for entry in audit_entries:
        if not isinstance(entry, AuditEntry):
            raise TypeError("audit_entries must contain AuditEntry values")
        if entry.sequence.value != expected_sequence:
            raise ValueError("audit sequence must be contiguous and start at one")
        expected_sequence += 1
